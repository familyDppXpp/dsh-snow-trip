import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const {chromium}=await import(process.env.SNOW_PLAYWRIGHT||'playwright');
const url=process.env.SNOW_DSH_URL||(await readFile(process.env.SNOW_HOST_LOG,'utf8')).match(/http:\/\/127\.0\.0\.1:\d+[^\s\x1b]*/)?.[0];
const browser=await chromium.launch({headless:true,...(process.env.SNOW_CHROME?{executablePath:process.env.SNOW_CHROME}:{})});
try {
  const page=await browser.newPage({viewport:{width:1100,height:900}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(url,{waitUntil:'networkidle'});
  await page.getByRole('button',{name:'打开雪季出行工作台',exact:true}).click();
  const panel=page.getByRole('dialog',{name:'雪季出行工作台',exact:true});
  await panel.getByRole('button',{name:'新增会话',exact:true}).click();
  await panel.locator('.snow-conversation [contenteditable=true]').waitFor();
  const id=await page.evaluate(()=>window.snowSessionCheck.state().current);
  const row=()=>panel.locator(`.snow-session-row[data-session-id="${id}"]`);
  const modal=page.getByRole('dialog',{name:'编辑会话标题',exact:true});
  await panel.getByRole('button',{name:'找出行方案',exact:true}).click();
  assert.equal(await panel.locator('.snow-session-heading').count(),0);
  await row().getByRole('button',{name:/会话操作/}).click();
  await page.getByRole('menu',{name:'会话操作',exact:true}).getByRole('menuitem',{name:'重命名',exact:true}).click();
  await modal.getByLabel('会话标题',{exact:true}).fill('不应保存的标题');
  await modal.getByRole('button',{name:'取消',exact:true}).click();
  assert.equal(await row().locator('strong').innerText(),'新会话');
  await row().getByRole('button',{name:/会话操作/}).click();
  await page.getByRole('menu',{name:'会话操作',exact:true}).getByRole('menuitem',{name:'重命名',exact:true}).click();
  await modal.getByLabel('会话标题',{exact:true}).fill('   ');
  await modal.getByRole('button',{name:'保存标题',exact:true}).click();
  await modal.getByRole('alert').getByText('请输入会话标题。',{exact:true}).waitFor();
  const title='长白山行程 · 标题编辑检查 '+Date.now();
  await modal.getByLabel('会话标题',{exact:true}).fill(title);
  await modal.getByLabel('会话标题',{exact:true}).press('Enter');
  await modal.waitFor({state:'detached'});
  await row().getByText(title,{exact:true}).waitFor();
  assert.equal(await page.evaluate(id=>window.snowSessionCheck.state().byId[id].title,id),title);
  await panel.getByRole('button',{name:'开始录入',exact:true}).first().waitFor();
  await page.reload({waitUntil:'networkidle'});
  await page.getByRole('button',{name:'打开雪季出行工作台',exact:true}).click();
  await row().getByText(title,{exact:true}).waitFor();
  await panel.getByLabel('搜索会话',{exact:true}).fill(title);
  assert.equal(await panel.locator('.snow-session-row').count(),1);
  await page.setViewportSize({width:390,height:844});
  await row().hover();
  assert.equal(await row().evaluate(e=>e.scrollWidth>e.clientWidth+1),false);
  await page.screenshot({path:'.local/session-title-edit.png'});
  assert.deepEqual(errors,[]);
  console.log('通过：移除小节标题、取消不保存、空标题校验、Enter保存宿主标题、刷新保留、搜索新标题、窄屏操作按钮。');
} finally {await browser.close();}
