import assert from 'node:assert/strict';
import {readFile,mkdir} from 'node:fs/promises';
const {chromium}=await import(process.env.SNOW_PLAYWRIGHT||'playwright');
const url=process.env.SNOW_DSH_URL||(await readFile(process.env.SNOW_HOST_LOG,'utf8')).match(/http:\/\/127\.0\.0\.1:\d+[^\s\x1b]*/)?.[0];
const browser=await chromium.launch({headless:true,...(process.env.SNOW_CHROME?{executablePath:process.env.SNOW_CHROME}:{})});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(url,{waitUntil:'networkidle'});
  await page.getByRole('button',{name:'打开雪季出行工作台',exact:true}).click();
  const panel=page.getByRole('dialog',{name:'雪季出行工作台',exact:true});
  const search=panel.getByRole('textbox',{name:'搜索会话'});
  await search.waitFor();
  const existing=panel.locator('.snow-session-open[title="新会话"]');
  if(await existing.count())await existing.first().click();
  else await panel.getByRole('button',{name:'出发去山野',exact:true}).click();
  await panel.locator('.snow-conversation [contenteditable=true]').waitFor();
  const active=panel.locator('.snow-session-open[aria-current=page]');
  assert.equal(await active.locator('strong').innerText(),'新会话');
  await search.fill('没有这样的标题_检查');
  await panel.getByText('没有匹配的会话',{exact:true}).waitFor();
  assert.equal(await panel.locator('.snow-session-row').count(),0);
  await search.press('Escape');
  assert.equal(await search.inputValue(),'');
  assert.equal(await panel.isVisible(),true,'清空搜索不能关闭工作台');
  await search.fill('新会话');
  const titles=await panel.locator('.snow-session-open strong').allTextContents();
  assert.ok(titles.length>0&&titles.every(t=>t==='新会话'));
  await panel.getByRole('button',{name:'清空会话搜索'}).click();
  const row=panel.locator('.snow-session-row.is-current');
  await row.hover();
  const remove=row.getByRole('button',{name:'会话操作：新会话',exact:true});
  await remove.focus();
  await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='会话操作：新会话'&&getComputedStyle(document.activeElement.parentElement).opacity==='1');
  await remove.click();
  await page.getByRole('menu',{name:'会话操作',exact:true}).getByRole('menuitem',{name:'归档会话',exact:true}).click();
  const confirm=page.getByRole('dialog',{name:'归档会话',exact:true});
  await confirm.waitFor();
  await confirm.getByRole('button',{name:'取消',exact:true}).click();
  assert.equal(await active.count(),1);
  await panel.getByRole('button',{name:'找出行方案',exact:true}).click();
  const resize=page.getByRole('separator',{name:'调整侧边栏宽度'});
  await resize.press('End');for(let i=0;i<13;i++)await resize.press('ArrowLeft');
  await mkdir('.local',{recursive:true});
  await page.screenshot({path:'.local/session-list-desktop.png'});
  await page.setViewportSize({width:750,height:863});
  await resize.press('End');await resize.press('ArrowLeft');await resize.press('ArrowLeft');
  await page.screenshot({path:'.local/session-list-750.png'});
  await page.setViewportSize({width:390,height:844});
  await resize.press('Home');
  assert.equal(await panel.locator('.snow-session-list').evaluate(e=>e.scrollWidth>e.clientWidth+1),false);
  await page.screenshot({path:'.local/session-list-mobile.png'});
  assert.deepEqual(errors,[]);
  console.log('通过：新会话标题、搜索/空结果/Escape清空、当前项、归档确认、宽窄侧栏无横溢出。');
} finally {await browser.close();}
