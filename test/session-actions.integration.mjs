import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const {chromium}=await import(process.env.SNOW_PLAYWRIGHT||'playwright');
const url=process.env.SNOW_DSH_URL||(await readFile(process.env.SNOW_HOST_LOG,'utf8')).match(/http:\/\/127\.0\.0\.1:\d+[^\s\x1b]*/)?.[0];
const browser=await chromium.launch({headless:true,...(process.env.SNOW_CHROME?{executablePath:process.env.SNOW_CHROME}:{})});
try {
  const context=await browser.newContext(),page=await context.newPage();
  page.setDefaultTimeout(15000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(url,{waitUntil:'networkidle'});
  await page.getByRole('button',{name:'打开雪季出行工作台',exact:true}).click();
  const panel=page.getByRole('dialog',{name:'雪季出行工作台',exact:true});
  const source=await page.evaluate(()=>Object.values(window.snowSessionCheck.state().byId).find(r=>r.projectionValues?.agentPreset==='snow-trip'&&(r.title||r.displayTitle||'').includes('热身')&&!r.blank&&!r.running&&!window.snowSessionCheck.workspaces().archivedSessionIds.includes(r.id))?.id);
  assert.ok(source,'需要一个有完整回复的雪季会话用于验证分叉');
  const row=id=>panel.locator(`.snow-session-row[data-session-id="${id}"]`);
  async function menu(id,action){await row(id).getByRole('button',{name:/会话操作/}).click();await page.getByRole('menu',{name:'会话操作',exact:true}).getByRole('menuitem',{name:action,exact:true}).click();}
  await menu(source,'分叉会话');
  await page.waitForFunction(source=>window.snowSessionCheck.state().current!==source&&window.snowSessionCheck.state().byId[window.snowSessionCheck.state().current]?.parentId===source,source);
  const child=await page.evaluate(()=>window.snowSessionCheck.state().current);
  await row(child).waitFor();
  assert.equal(await page.evaluate(id=>window.snowSessionCheck.state().byId[id].projectionValues.agentPreset,child),'snow-trip');
  await panel.locator('.snow-conversation').getByText('请用中文解释滑雪前热身有什么作用，回答不超过三句话。',{exact:true}).waitFor();
  await menu(child,'重命名');
  const rename=page.getByRole('dialog',{name:'编辑会话标题',exact:true});
  await rename.getByLabel('会话标题',{exact:true}).fill('分叉归档验收');
  await rename.getByRole('button',{name:'保存标题',exact:true}).click();
  await rename.waitFor({state:'detached'});
  assert.equal(await page.evaluate(id=>window.snowSessionCheck.state().byId[id].title,child),'分叉归档验收');
  await menu(child,'归档会话');
  const archive=page.getByRole('dialog',{name:'归档会话',exact:true});
  await archive.getByRole('button',{name:'取消',exact:true}).click();
  assert.equal(await row(child).count(),1);
  assert.equal(await page.evaluate(id=>window.snowSessionCheck.workspaces().archivedSessionIds.includes(id),child),false);
  await menu(child,'归档会话');
  await archive.getByRole('button',{name:'确认归档',exact:true}).click();
  await archive.waitFor({state:'detached'});await row(child).waitFor({state:'detached'});
  assert.equal(await page.evaluate(id=>window.snowSessionCheck.workspaces().archivedSessionIds.includes(id),child),true);
  assert.ok(await page.evaluate(id=>window.snowSessionCheck.state().byId[id],child),'归档保留会话记录');
  const other=await browser.newContext(),second=await other.newPage();
  await second.goto(url,{waitUntil:'networkidle'});await second.getByRole('button',{name:'打开雪季出行工作台',exact:true}).click();
  await second.waitForFunction(id=>window.snowSessionCheck.workspaces().archivedSessionIds.includes(id),child);
  assert.equal(await second.locator(`.snow-session-row[data-session-id="${child}"]`).count(),0);
  await page.reload({waitUntil:'networkidle'});await page.getByRole('button',{name:'打开雪季出行工作台',exact:true}).click();
  assert.equal(await row(child).count(),0);await row(source).waitFor();
  await page.setViewportSize({width:390,height:844});await row(source).getByRole('button',{name:/会话操作/}).click();
  await page.screenshot({path:'.local/session-actions.png'});
  assert.deepEqual(errors,[]);
  console.log('通过：原生分叉保留历史及预设、重命名、归档取消与确认、宿主归档状态、独立浏览器同步、刷新保留、原会话不受影响。');
}finally{await browser.close();}
